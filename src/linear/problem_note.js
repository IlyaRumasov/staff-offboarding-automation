// Коментар у заявку, коли AD-крок неможливий або впав. Заявка лишається відкритою.
// Формат: що перевірено, результат, що робити далі. notify = false, якщо про цю саму проблему вже писали.
const d = $('Code: Decide AD Action').first().json;
const inp = $input.first().json;
const state = $getWorkflowStaticData('global');
state.notified_run = state.notified_run || {};

const err = inp.error ? String(inp.error.message || inp.error.description || inp.error) : '';
const reason = err ? 'ad_error' : d.ad_status;
const guest = d.guest_email || `<логін>_example.com@tenant.example.org.guest.google`;
const byLogin = `• Пошук в AD за логіном (sAMAccountName) «${d.login}» по всьому домену, включно з OU «Уволенные».`;
const variants = (d.pairs || [[d.gn, d.sn]]).map(p => p.join(' ')).join(' / ');
const byName = `• AD-логін у заявці не вказано (рядок «AD -» порожній).\n` +
  `• ПІБ із заявки: «${d.fio}», варіанти латиницею: ${variants}.\n` +
  `• Пошук в AD за прізвищем і звірка імені за кожним варіантом.`;
const closeByHand = `якщо акаунт в AD уже видалено вручну, перевірте, чи немає гостьового акаунта Google (${guest}), і закрийте заявку вручну.`;

const T = {
  not_found: [byLogin, `акаунт «${d.login}» не знайдено в AD.`, [
    'перевірте логін у рядку «AD -» (можлива помилка в логіні); після виправлення автоматизація обробить заявку сама;', closeByHand]],
  multiple: [byLogin, `за логіном «${d.login}» знайдено кілька акаунтів: ${d.candidates}. Потрібна ручна перевірка.`, [
    'визначте, який акаунт належить працівнику, і заблокуйте його вручну;', 'закрийте заявку вручну.']],
  outside_scope: [byLogin, `акаунт знайдено поза OU=AllUsers (${d.dn}). Автоматичне блокування для нього вимкнене, потрібна ручна перевірка.`, [
    'перевірте, чи це той самий працівник (можливо, адмін-персонал або службовий акаунт);',
    'якщо так, заблокуйте його вручну і закрийте заявку; якщо ні, виправте логін у рядку «AD -».']],
  fired_but_enabled: [byLogin, `акаунт уже в OU «Уволенные», але не заблокований (${d.dn}).`, [
    'заблокуйте акаунт вручну (Disable Account);', 'далі автоматизація сама видалить гостьовий акаунт Google і закриє заявку.']],
  name_not_found: [byName, `акаунт в AD не знайдено.` + (d.candidates ? ` З таким прізвищем є: ${d.candidates}.` : ' Людей із таким прізвищем в AD немає.'), [
    'якщо знаєте логін, впишіть його в рядок «AD -», і автоматизація обробить заявку сама;', closeByHand]],
  name_tenure_mismatch: [byName, `акаунт із таким іменем є (${d.candidates}), але дата його створення не збігається з тривалістю співпраці із заявки (${d.tenure_days} дн. до ${d.leaver_date}). Схоже, це інша людина або старий дублікат, автоматично не блокуємо.`, [
    'перевірте, чи це акаунт працівника, і впишіть його логін у рядок «AD -»;', 'якщо акаунт працівника інший, автоматизація обробить заявку після виправлення логіна.']],
  name_multiple: [byName, `знайдено кілька акаунтів з таким іменем і прізвищем: ${d.candidates}. Автоматично обрати не можна.`, [
    'визначте, який акаунт належить працівнику, і впишіть його логін у рядок «AD -»;', 'автоматизація обробить заявку під час наступного запуску.']],
  ad_error: [d.found_by_name ? byName + `\n• Знайдено акаунт: ${d.login} (${d.dn}).` : byLogin + `\n• Знайдено акаунт: ${d.dn}.`,
    `не вдалося заблокувати або перемістити акаунт в AD: ${err}`, [
    'перевірте права сервісного облікового запису n8n в AD (блокування й переміщення в OU «Уволенные») і доступність контролера домену;',
    'автоматизація повторить спробу під час наступного запуску; або виконайте блокування вручну.']],
};
const [checked, result, next] = T[reason] || ['', reason, []];

const key = reason + ':' + (reason === 'ad_error' ? '' : d.dn + '|' + d.candidates);
const notify = state.notified_run[d.id] !== key;
state.notified_run[d.id] = key;

return [{ json: {
  id: d.id, close: false, reason, notify,
  note: `⚠ Автоматичний offboarding не виконано.\n\nЩо перевірено:\n${checked}\n\nРезультат: ${result}\n\n` +
        `Що робити далі:\n${next.map((s, i) => `${i + 1}. ${s.charAt(0).toUpperCase()}${s.slice(1)}`).join('\n')}\n\n` +
        'Заявку залишено відкритою. ' + (reason === 'ad_error' ? 'Google не змінено; стан акаунта в AD перевірте вручну (блокування могло пройти без переміщення). ' : 'Нічого в AD і Google не змінено. ') + 'Автоматизація перевіряє заявку щодня о 18:00; про ту саму проблему повторно не пише.',
}, pairedItem: { item: 0 } }];
